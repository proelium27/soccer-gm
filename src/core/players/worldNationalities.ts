/**
 * Every remaining FIFA member association, so that ANY country can be the home
 * nation of a league the player builds.
 *
 * The world editor lets a player author a league's nationality mix, but it can
 * only offer nations the game ships names for — so before this, "add a Taiwanese
 * league" was not a thing the game could do, and picking Taiwan in a roster file
 * silently dropped the row (`sanitizeNationalityWeights` refuses a nation with no
 * name pool). The 110 nations that already had pools were the ones some shipped
 * league's real breakdown happened to name; that is a fine reason for a *tail*
 * and a bad reason for a *catalogue*. These 101 complete it, taking the pickable
 * set to all 211 FIFA members.
 *
 * **These are merged into UNLISTED_NATIONALITIES, and that is the whole safety
 * argument.** `TAIL_BASE` — the "Rest of the World" tail every league draws
 * from — is built from `NATIONALITIES` + `OTHER_NATIONS` only. A nation here is
 * therefore reachable ONLY when a table names it explicitly, so adding a hundred
 * of them cannot re-weight the tail draw of any league in any existing save, and
 * cannot put a Bhutanese full-back in the Bundesliga by accident. Pinned by
 * `customNationalities.test.ts`, which asserts the tail is untouched. Putting
 * them in `OTHER_NATIONS` instead would change generated players in every save
 * ever made — do not "tidy" them there.
 *
 * `weight` is inert for an unlisted nation (nothing reads it for a flat draw);
 * it records where the entry would sit if it were ever graduated. They are all 1
 * because none of these has a shipped league to calibrate against.
 *
 * Pools are 56 first x 56 last (3,136 names), the same floor the 2026-08-26
 * expansion set: any of these can now be a league's home nation and supply ~1000
 * players, which is the case the floor was sized for. Names are common civilian
 * names, ASCII-only and deliberately NOT the names of real footballers — a
 * generated player must never read as a real pro. `nationalities.test.ts` pins
 * the size floor, the ASCII rule and within-list uniqueness;
 * `international.test.ts` pins that each one has a confederation.
 *
 * Most have no flag art (`<Flag>` renders its neutral swatch), which is the call
 * `flags.ts` already documents: many of these need a coat of arms or Arabic
 * calligraphy, and the shipped flags are hand-written SVGs, so a wrong flag reads
 * worse than none. The simple geometric ones did get art.
 */
